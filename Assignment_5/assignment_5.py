def output_decorator(parameter):
    def decorator(func):
        def wrapper(*args, **kwargs):
            print("#", parameter)
            print("# input:", ", ".join(str(x) for x in args))
            result = func(*args, **kwargs)
            print("# output:", result)
            return result
        return wrapper
    return decorator
@output_decorator("Adding")
def add(a, b):
    return a + b
